<!-- What is Down Syndrome? Start -->
<div class="container-xxl py-5 bg-light-blue">
    <div class="container">
        <div class="row g-5">
            <div class="col-lg-6 wow fadeInUp" data-wow-delay="0.1s">
                <h2 class="section-title h1">What is Down Syndrome?</h2>
                <p class="mission-text">Down syndrome (also called Trisomy 21) is a genetic condition where a person is born with an extra copy of chromosome 21. This additional genetic material affects the way the body and brain develop, but it does not define who a person is. It occurs in all races, cultures, and economic levels, and it is the most common chromosomal condition, occurring in about 1 in every 700 births worldwide.</p>
                <p class="mission-text">There are three types of Down syndrome:</p>
                <ul class="list-unstyled">
                    <li class="mb-2"><i class="fas fa-check-circle text-warning me-2"></i> <strong>Trisomy 21</strong> (95% of cases) – every cell has three copies of chromosome 21.</li>
                    <li class="mb-2"><i class="fas fa-check-circle text-warning me-2"></i> <strong>Translocation</strong> (about 3%) – an extra part of chromosome 21 is attached to another chromosome.</li>
                    <li class="mb-2"><i class="fas fa-check-circle text-warning me-2"></i> <strong>Mosaicism</strong> (about 2%) – only some cells have an extra chromosome 21.</li>
                </ul>
            </div>
            <div class="col-lg-6 wow fadeInUp" data-wow-delay="0.5s">
                <div class="bg-white p-4 rounded shadow">
                    <h4 class="text-primary mb-3"><i class="fas fa-dna text-warning me-2"></i> Chromosome 21</h4>
                    <p>Every person typically has 23 pairs of chromosomes. In Down syndrome, there is a full or partial extra copy of chromosome 21, which is why it is also called Trisomy 21.</p>
                    <img class="img-fluid mt-3 rounded" src="images/chromosome-diagram.jpg" alt="Chromosome 21 diagram">
                </div>
            </div>
        </div>
    </div>
</div>
