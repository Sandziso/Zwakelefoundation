        <div class="row g-5 align-items-center">
            <div class="col-lg-6 wow fadeInUp" data-wow-delay="0.1s">
                <h2 class="section-title h1">What Causes Down Syndrome?</h2>
                <p class="mission-text">Down syndrome is caused by an error in cell division called nondisjunction. This happens randomly at the time of conception and is not linked to anything parents did or did not do. There is no known way to prevent it, and it occurs in families of all backgrounds. The only known risk factor is maternal age – the chance increases as a woman gets older – but most babies with Down syndrome are born to younger mothers because they have more babies.</p>
                <p class="mission-text">It is important to understand that Down syndrome is not a punishment or a mistake – it is simply a part of human diversity.</p>
            </div>
