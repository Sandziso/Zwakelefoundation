                <h2 class="section-title h1">Health Considerations</h2>
                <p class="mission-text">People with Down syndrome may have an increased risk for certain medical conditions, but with proper healthcare, most lead healthy lives. Regular check‑ups and early intervention are key.</p>
                <ul class="list-unstyled">
                    <li class="mb-2"><i class="fas fa-heartbeat text-warning me-2"></i> <strong>Heart defects:</strong> About half are born with a heart condition – many can be surgically corrected.</li>
                    <li class="mb-2"><i class="fas fa-lungs text-warning me-2"></i> <strong>Respiratory & hearing issues:</strong> Frequent ear infections, sleep apnoea.</li>
                    <li class="mb-2"><i class="fas fa-eye text-warning me-2"></i> <strong>Vision problems:</strong> Cataracts, near/farsightedness.</li>
                    <li class="mb-2"><i class="fas fa-thyroid text-warning me-2"></i> <strong>Thyroid conditions:</strong> Hypothyroidism is more common.</li>
                    <li class="mb-2"><i class="fas fa-dumbbell text-warning me-2"></i> <strong>Low muscle tone:</strong> Can affect motor skills, but physical therapy helps.</li>
                </ul>
                <p class="mt-3">With access to good medical care, most of these conditions can be managed effectively.</p>
